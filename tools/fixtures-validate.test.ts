import { cpSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { validateAllSamples, validateSampleDir } from './fixtures-validate.ts';

const dataRoot = new URL('../packages/samples/data', import.meta.url).pathname;

describe('committed sample data', () => {
  it('passes validation', () => {
    expect(validateAllSamples(dataRoot)).toEqual([]);
  });

  it('is marked as generated by real Terraform with pinned provider versions', () => {
    for (const id of ['haunted', 'web']) {
      const meta = JSON.parse(readFileSync(join(dataRoot, id, 'meta.json'), 'utf8'));
      expect(meta.generated).toBe(true);
      expect(meta.providers['hashicorp/aws']).toMatch(/^\d+\.\d+\.\d+$/);
    }
  });
});

describe('validateSampleDir', () => {
  const scratch: string[] = [];
  afterEach(() => {
    for (const dir of scratch.splice(0)) rmSync(dir, { recursive: true, force: true });
  });

  const copySample = (id: string) => {
    const root = mkdtempSync(join(tmpdir(), 'cloudverse-validate-'));
    scratch.push(root);
    const dir = join(root, id);
    cpSync(join(dataRoot, id), dir, { recursive: true });
    return dir;
  };

  it('reports missing files', () => {
    const root = mkdtempSync(join(tmpdir(), 'cloudverse-validate-'));
    scratch.push(root);
    expect(validateSampleDir(root, 'haunted')).toEqual([
      'haunted: missing plan.json',
      'haunted: missing meta.json',
      'haunted: missing snippets.json',
    ]);
  });

  it('reports a resource without an HCL snippet and a snippet without a resource', () => {
    const dir = copySample('haunted');
    const snippets = JSON.parse(readFileSync(join(dir, 'snippets.json'), 'utf8')) as Record<string, string>;
    delete snippets['aws_vpc.kingdom'];
    snippets['aws_vpc.ghost'] = 'resource "aws_vpc" "ghost" {}';
    writeFileSync(join(dir, 'snippets.json'), JSON.stringify(snippets));

    const problems = validateSampleDir(dir, 'haunted');
    expect(problems).toContain('haunted: no HCL snippet for aws_vpc.kingdom');
    expect(problems).toContain('haunted: snippet aws_vpc.ghost has no matching resource in the plan');
  });

  it('reports a meta id that does not match the directory', () => {
    const dir = copySample('web');
    const meta = JSON.parse(readFileSync(join(dir, 'meta.json'), 'utf8'));
    writeFileSync(join(dir, 'meta.json'), JSON.stringify({ ...meta, id: 'other' }));
    expect(validateSampleDir(dir, 'web').join('\n')).toMatch(/must match directory name/);
  });

  it('reports a malformed plan', () => {
    const dir = copySample('web');
    writeFileSync(join(dir, 'plan.json'), JSON.stringify({ not: 'a plan' }));
    expect(validateSampleDir(dir, 'web').some((p) => p.includes('plan.json'))).toBe(true);
  });
});

describe('validateAllSamples', () => {
  it('reports a missing data directory', () => {
    expect(validateAllSamples('/definitely/not/here')[0]).toMatch(/not found/);
  });
});
